// Keeps ONE source of truth for the calculation engine: ../free/calc-engine.js.
// premium/src/vendor/calc-engine.js is a byte-for-byte generated copy (so a Premium-only deploy still builds).
//   node scripts/sync-engine.mjs          copy Free -> vendor
//   node scripts/sync-engine.mjs --check  fail if they differ (used by tests / CI)
import { copyFileSync, existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../free/calc-engine.js");
const target = resolve(here, "../src/vendor/calc-engine.js");
const versionFile = resolve(here, "../src/vendor/engine-version.ts");
const versionSource = (src) => `// GENERATED by scripts/sync-engine.mjs from free/calc-engine.js. Do not edit.\nexport const ENGINE_VERSION = "${createHash("sha256").update(src).digest("hex").slice(0, 12)}";\n`;
const check = process.argv.includes("--check");
if (!existsSync(source)) {
  if (existsSync(target)) { console.warn("sync-engine: ../free not found; using the committed vendor copy."); process.exit(0); }
  console.error("sync-engine: neither ../free/calc-engine.js nor the vendor copy exists."); process.exit(1);
}
if (check) {
  const same = existsSync(target) && readFileSync(source).equals(readFileSync(target)) && existsSync(versionFile) && readFileSync(versionFile, "utf8") === versionSource(readFileSync(source));
  if (!same) { console.error("sync-engine: vendor copy differs from free/calc-engine.js. Run: node scripts/sync-engine.mjs"); process.exit(1); }
  console.log("sync-engine: vendor copy is identical to free/calc-engine.js"); process.exit(0);
}
mkdirSync(dirname(target), { recursive: true });
copyFileSync(source, target);
writeFileSync(versionFile, versionSource(readFileSync(source)));
console.log("sync-engine: copied free/calc-engine.js -> src/vendor/calc-engine.js");
