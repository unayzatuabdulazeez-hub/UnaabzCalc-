// Generates supabase/tests/20_has_premium_parity.sql from the TypeScript entitlement rules, so the SQL function
// public.has_premium() and src/lib/entitlements/resolve.ts can never silently disagree.
//   npx tsx scripts/gen-parity-sql.ts      (rewrites the file)
// A unit test fails if the committed file is out of date.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { resolveEntitlement, ENTITLEMENT_STATUSES } from "../src/lib/entitlements/resolve";

const DAY = 86400000;
const off = (now: Date, d: number | null) => (d === null ? null : new Date(now.getTime() + d * DAY).toISOString());
const sqlOff = (d: number | null) => (d === null ? "null" : `now() + interval '${d} days'`);

export function buildParitySql(now: Date): string {
  const rows: string[] = [];
  const pays = ["none", "paid"];
  const starts = [null, -5, 5], ends = [null, -3, 3];
  for (const status of ENTITLEMENT_STATUSES) for (const pay of pays)
    for (const ss of starts) for (const se of ends) for (const ts of starts) for (const te of ends) {
      // The database forbids end < start (check constraints), so those rows can never exist.
      if ((ss !== null && se !== null && se < ss) || (ts !== null && te !== null && te < ts)) continue;
      const res = resolveEntitlement({
        status, payment_status: pay,
        subscription_start: off(now, ss), subscription_end: off(now, se), trial_start: off(now, ts), trial_end: off(now, te),
      }, now);
      rows.push(`  ('${status}','${pay}',${sqlOff(ss)},${sqlOff(se)},${sqlOff(ts)},${sqlOff(te)},${res.hasPremium})`);
    }
  return `-- GENERATED by scripts/gen-parity-sql.ts. Do not edit by hand.
-- Checks that public.has_premium() agrees with resolveEntitlement() for ${rows.length} status/date combinations.
\\set ON_ERROR_STOP on
create temp table parity (status text, pay text, ss timestamptz, se timestamptz, ts timestamptz, te timestamptz, expected boolean);
insert into parity values
${rows.join(",\n")};
do $$
declare r record; uid uuid; got boolean; bad int := 0; n int := 0;
begin
  for r in select * from parity loop
    uid := gen_random_uuid();
    insert into auth.users (id, email) values (uid, uid::text || '@parity.test');
    update public.entitlements set status = r.status::public.entitlement_status, payment_status = r.pay,
      subscription_start = r.ss, subscription_end = r.se, trial_start = r.ts, trial_end = r.te where user_id = uid;
    perform set_config('request.jwt.claim.sub', uid::text, true);
    got := public.has_premium();
    n := n + 1;
    if got is distinct from r.expected then bad := bad + 1; if bad <= 10 then raise notice 'MISMATCH % pay=% ss=% se=% ts=% te=% sql=% ts_rule=%', r.status, r.pay, r.ss, r.se, r.ts, r.te, got, r.expected; end if; end if;
  end loop;
  raise notice 'PARITY TOTAL % MISMATCHES %', n, bad;
  if bad > 0 then raise exception 'has_premium() disagrees with resolveEntitlement() in % cases', bad; end if;
end $$;
`;
}
if (process.argv[1] && process.argv[1].endsWith("gen-parity-sql.ts")) {
  const out = join(__dirname, "../supabase/tests/20_has_premium_parity.sql");
  writeFileSync(out, buildParitySql(new Date()));
  console.log("wrote", out);
}
